// пропорции оригинала: значок шире, чем выше, поэтому size задаёт высоту
const RATIO = 76 / 64;

export function GramIcon({ size = 16, className }: { size?: number; className?: string }) {
  return (
    <svg
      className={className}
      width={Math.round(size * RATIO)}
      height={size}
      viewBox="0 0 76 64"
      fill="none"
      aria-hidden="true"
      focusable="false"
    >
      <path fillRule="evenodd" clipRule="evenodd" d={GRAM_PATH} fill="currentColor" />
    </svg>
  );
}

/** Сумма: логотип Gram + число. Текстовую подпись валюты не дублируем. */
export function GramAmount({
  value,
  size = 16,
  className,
}: {
  value: string | number;
  size?: number;
  className?: string;
}) {
  return (
    <span className={className ? `gram-amount ${className}` : "gram-amount"}>
      <GramIcon size={size} className="gram-amount-icon" />
      {value}
    </span>
  );
}
